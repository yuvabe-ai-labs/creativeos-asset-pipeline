// Regenerates src/lib/editor/caption-font-coverage.ts from the caption fonts' cmap tables (D393).
// Run after replacing a font file: node --experimental-strip-types scripts/gen-caption-font-coverage.mjs
// The caption-fonts test fails until this has been run.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { codepointRanges, readCmapCodepoints } from "../src/lib/editor/font-name.ts";

const FILES = {
  montserrat: "Montserrat-ExtraBold.ttf",
  poppins: "Poppins-Bold.ttf",
  "bebas-neue": "BebasNeue-Regular.ttf",
  anton: "Anton-Regular.ttf",
  "playfair-display": "PlayfairDisplay-Bold.ttf",
};
const dir = path.join(process.cwd(), "src/fonts/captions");
const lines = Object.entries(FILES).map(([key, file]) => {
  const ranges = codepointRanges(readCmapCodepoints(new Uint8Array(readFileSync(path.join(dir, file)))));
  return `  ${JSON.stringify(key)}: ${JSON.stringify(ranges)},`;
});
writeFileSync(
  path.join(process.cwd(), "src/lib/editor/caption-font-coverage.ts"),
  [
    "// GENERATED by scripts/gen-caption-font-coverage.mjs from src/fonts/captions — do not edit.",
    "// Which characters each caption font can draw: inclusive codepoint ranges (D393).",
    'import type { CaptionFontKey } from "./caption-fonts";',
    "",
    "export const CAPTION_FONT_COVERAGE: Record<CaptionFontKey, Array<[number, number]>> = {",
    ...lines,
    "};",
    "",
  ].join("\n"),
);
console.log("wrote caption-font-coverage.ts");
