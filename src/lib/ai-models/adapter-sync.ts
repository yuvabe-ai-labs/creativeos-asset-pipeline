// D538 — migration 0084's rows: each image and video model's own adapter key and the provider's
// name for it, and its data re-synced from the registries. Test-only builder: the drift test
// (adapter-sync.test.ts) keeps 0084 equal to it until Plan 1b-iii deletes the registries and
// freezes 0084. Not imported by app code.
import { seedRowsFromRegistries, SEED_JSON_TAG } from "./seed";
import type { ParamSpec } from "@/lib/image-gen/types";
import type { ConstraintRule } from "@/lib/video-gen/types";
import { SEEDREAM_LITE, SEEDREAM_PRO } from "@/lib/image-gen/providers/seedream";
import { KLING_VENDOR_MODELS } from "@/lib/video-gen/providers/kling";
import { SEEDANCE_VENDOR_MODEL } from "@/lib/video-gen/providers/seedance";
import { OMNI_11_API_MODEL, OMNI_12_API_MODEL } from "@/lib/video-gen/providers/gemini-omni";
import { VEO_MODEL_IDS } from "@/lib/video-gen/providers/veo";

export type AdapterSyncRow = {
  id: string;
  label: string;
  picker_label: string | null;
  provider_label: string;
  adapter_key: string;
  provider_model_id: string;
  params: ParamSpec[];
  rules: ConstraintRule[];
  capabilities: Record<string, unknown>;
};

/** Our id after the provider prefix: `openai:gpt-image-2` → `gpt-image-2`. */
const nameOf = (id: string) => id.slice(id.indexOf(":") + 1);

// The provider's own model names, from the constants the providers send. OpenAI and Gemini
// image models are sent under our id's name (providers/openai.ts, providers/gemini.ts).
const VENDOR_NAMES: Record<string, string> = {
  "seedream:seedream-5-0-lite": SEEDREAM_LITE.arkModel,
  "seedream:seedream-5-0-pro": SEEDREAM_PRO.arkModel,
  "kling:kling-3-0": KLING_VENDOR_MODELS["kling-3-0"],
  "kling:kling-o1": KLING_VENDOR_MODELS["kling-o1"],
  "kling:kling-3-0-omni": KLING_VENDOR_MODELS["kling-3-0-omni"],
  "seedance:seedance-2-5": SEEDANCE_VENDOR_MODEL,
  "gemini:gemini-omni-1.2-flash": OMNI_12_API_MODEL,
  "gemini:gemini-omni-1.1-flash": OMNI_11_API_MODEL,
  "veo:veo-3.1-lite": VEO_MODEL_IDS.lite,
  "veo:veo-3.1-fast": VEO_MODEL_IDS.fast,
  "veo:veo-3.1": VEO_MODEL_IDS.quality,
};

function vendorName(row: { id: string; kind: string; provider: string }): string {
  const known = VENDOR_NAMES[row.id];
  if (known) return known;
  if (row.kind === "image" && (row.provider === "openai" || row.provider === "gemini")) return nameOf(row.id);
  throw new Error(`No provider model name for ${row.id}: add it to VENDOR_NAMES`);
}

export function adapterSyncRows(): AdapterSyncRow[] {
  return seedRowsFromRegistries().map((r) => ({
    id: r.id,
    label: r.label,
    picker_label: r.picker_label,
    provider_label: r.provider_label,
    adapter_key: `${r.kind}:${nameOf(r.id)}`,
    provider_model_id: vendorName(r),
    params: r.params,
    rules: r.rules,
    capabilities: r.capabilities,
  }));
}

export const ADAPTER_SYNC_HEADER = [
  "-- D538: each image and video model's own adapter key and the provider's name for it, and its",
  "-- label, params, rules and capabilities re-synced from the registries. Status, replacement and",
  "-- order belong to the super admin and are left alone. Apply BEFORE the 1b-i code deploys.",
  "-- Generated by src/lib/ai-models/adapter-sync.ts. Regenerate with:",
  "--   UPDATE_SEED=1 npx vitest run src/lib/ai-models/__tests__/adapter-sync.test.ts",
];

export function adapterSyncSql(rows: AdapterSyncRow[]): string {
  const json = JSON.stringify(rows, null, 2);
  if (json.includes(SEED_JSON_TAG)) throw new Error(`Seed JSON contains ${SEED_JSON_TAG}`);
  return [
    ...ADAPTER_SYNC_HEADER,
    "update ai_models m set",
    "  label = r.label, picker_label = r.picker_label, provider_label = r.provider_label,",
    "  adapter_key = r.adapter_key, provider_model_id = r.provider_model_id,",
    "  params = r.params, rules = r.rules, capabilities = r.capabilities, updated_at = now()",
    `from jsonb_to_recordset(${SEED_JSON_TAG}${json}${SEED_JSON_TAG}::jsonb) as r(`,
    "  id text, label text, picker_label text, provider_label text, adapter_key text,",
    "  provider_model_id text, params jsonb, rules jsonb, capabilities jsonb",
    ")",
    "where m.id = r.id;",
    "",
  ].join("\n");
}
